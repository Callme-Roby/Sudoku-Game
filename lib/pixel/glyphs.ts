const pathCache = new WeakMap<Bitmap, string>();

/** One SVG path made of horizontal pixel runs. */
export function bitmapPath(rows: Bitmap): string {
  const hit = pathCache.get(rows);
  if (hit) return hit;
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === '#') end++;
      d += `M${x} ${y}h${end - x}v1h${x - end}z`;
      x = end;
    }
  });
  pathCache.set(rows, d);
  return d;
}
